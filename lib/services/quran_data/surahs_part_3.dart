    "عٓسٓقٓ",
    "كَذَٰلِكَ يُوحِىٓ إِلَيْكَ وَإِلَى الَّذِينَ مِن قَبْلِكَ اللَّهُ الْعَزِيزُ الْحَكِيمُ",
    "لَهُۥ مَا فِى السَّمَٰوَٰتِ وَمَا فِى الْأَرْضِ  وَهُوَ الْعَلِىُّ الْعَظِيمُ",
    "تَكَادُ السَّمَٰوَٰتُ يَتَفَطَّرْنَ مِن فَوْقِهِنَّ  وَالْمَلَٰٓئِكَةُ يُسَبِّحُونَ بِحَمْدِ رَبِّهِمْ وَيَسْتَغْفِرُونَ لِمَن فِى الْأَرْضِ  أَلَآ إِنَّ اللَّهَ هُوَ الْغَفُورُ الرَّحِيمُ",
    "وَالَّذِينَ اتَّخَذُوا مِن دُونِهِۦٓ أَوْلِيَآءَ اللَّهُ حَفِيظٌ عَلَيْهِمْ وَمَآ أَنتَ عَلَيْهِم بِوَكِيلٍ",
    "وَكَذَٰلِكَ أَوْحَيْنَآ إِلَيْكَ قُرْءَانًا عَرَبِيًّا لِّتُنذِرَ أُمَّ الْقُرَىٰ وَمَنْ حَوْلَهَا وَتُنذِرَ يَوْمَ الْجَمْعِ لَا رَيْبَ فِيهِ  فَرِيقٌ فِى الْجَنَّةِ وَفَرِيقٌ فِى السَّعِيرِ",
    "وَلَوْ شَآءَ اللَّهُ لَجَعَلَهُمْ أُمَّةً وَٰحِدَةً وَلَٰكِن يُدْخِلُ مَن يَشَآءُ فِى رَحْمَتِهِۦ  وَالظَّٰلِمُونَ مَا لَهُم مِّن وَلِىٍّ وَلَا نَصِيرٍ",
    "أَمِ اتَّخَذُوا مِن دُونِهِۦٓ أَوْلِيَآءَ  فَاللَّهُ هُوَ الْوَلِىُّ وَهُوَ يُحْىِ الْمَوْتَىٰ وَهُوَ عَلَىٰ كُلِّ شَىْءٍ قَدِيرٌ",
    "وَمَا اخْتَلَفْتُمْ فِيهِ مِن شَىْءٍ فَحُكْمُهُۥٓ إِلَى اللَّهِ  ذَٰلِكُمُ اللَّهُ رَبِّى عَلَيْهِ تَوَكَّلْتُ وَإِلَيْهِ أُنِيبُ",
    "فَاطِرُ السَّمَٰوَٰتِ وَالْأَرْضِ  جَعَلَ لَكُم مِّنْ أَنفُسِكُمْ أَزْوَٰجًا وَمِنَ الْأَنْعَٰمِ أَزْوَٰجًا  يَذْرَؤُكُمْ فِيهِ  لَيْسَ كَمِثْلِهِۦ شَىْءٌ  وَهُوَ السَّمِيعُ الْبَصِيرُ",
    "لَهُۥ مَقَالِيدُ السَّمَٰوَٰتِ وَالْأَرْضِ  يَبْسُطُ الرِّزْقَ لِمَن يَشَآءُ وَيَقْدِرُ  إِنَّهُۥ بِكُلِّ شَىْءٍ عَلِيمٌ",
    "۞ شَرَعَ لَكُم مِّنَ الدِّينِ مَا وَصَّىٰ بِهِۦ نُوحًا وَالَّذِىٓ أَوْحَيْنَآ إِلَيْكَ وَمَا وَصَّيْنَا بِهِۦٓ إِبْرَٰهِيمَ وَمُوسَىٰ وَعِيسَىٰٓ  أَنْ أَقِيمُوا الدِّينَ وَلَا تَتَفَرَّقُوا فِيهِ  كَبُرَ عَلَى الْمُشْرِكِينَ مَا تَدْعُوهُمْ إِلَيْهِ  اللَّهُ يَجْتَبِىٓ إِلَيْهِ مَن يَشَآءُ وَيَهْدِىٓ إِلَيْهِ مَن يُنِيبُ",
    "وَمَا تَفَرَّقُوٓا إِلَّا مِن بَعْدِ مَا جَآءَهُمُ الْعِلْمُ بَغْيًا بَيْنَهُمْ  وَلَوْلَا كَلِمَةٌ سَبَقَتْ مِن رَّبِّكَ إِلَىٰٓ أَجَلٍ مُّسَمًّى لَّقُضِىَ بَيْنَهُمْ  وَإِنَّ الَّذِينَ أُورِثُوا الْكِتَٰبَ مِن بَعْدِهِمْ لَفِى شَكٍّ مِّنْهُ مُرِيبٍ",
    "فَلِذَٰلِكَ فَادْعُ  وَاسْتَقِمْ كَمَآ أُمِرْتَ  وَلَا تَتَّبِعْ أَهْوَآءَهُمْ  وَقُلْ ءَامَنتُ بِمَآ أَنزَلَ اللَّهُ مِن كِتَٰبٍ  وَأُمِرْتُ لِأَعْدِلَ بَيْنَكُمُ  اللَّهُ رَبُّنَا وَرَبُّكُمْ  لَنَآ أَعْمَٰلُنَا وَلَكُمْ أَعْمَٰلُكُمْ  لَا حُجَّةَ بَيْنَنَا وَبَيْنَكُمُ  اللَّهُ يَجْمَعُ بَيْنَنَا  وَإِلَيْهِ الْمَصِيرُ",
    "وَالَّذِينَ يُحَآجُّونَ فِى اللَّهِ مِن بَعْدِ مَا اسْتُجِيبَ لَهُۥ حُجَّتُهُمْ دَاحِضَةٌ عِندَ رَبِّهِمْ وَعَلَيْهِمْ غَضَبٌ وَلَهُمْ عَذَابٌ شَدِيدٌ",
    "اللَّهُ الَّذِىٓ أَنزَلَ الْكِتَٰبَ بِالْحَقِّ وَالْمِيزَانَ  وَمَا يُدْرِيكَ لَعَلَّ السَّاعَةَ قَرِيبٌ",
    "يَسْتَعْجِلُ بِهَا الَّذِينَ لَا يُؤْمِنُونَ بِهَا  وَالَّذِينَ ءَامَنُوا مُشْفِقُونَ مِنْهَا وَيَعْلَمُونَ أَنَّهَا الْحَقُّ  أَلَآ إِنَّ الَّذِينَ يُمَارُونَ فِى السَّاعَةِ لَفِى ضَلَٰلٍ بَعِيدٍ",
    "اللَّهُ لَطِيفٌ بِعِبَادِهِۦ يَرْزُقُ مَن يَشَآءُ  وَهُوَ الْقَوِىُّ الْعَزِيزُ",
    "مَن كَانَ يُرِيدُ حَرْثَ الَْٔاخِرَةِ نَزِدْ لَهُۥ فِى حَرْثِهِۦ  وَمَن كَانَ يُرِيدُ حَرْثَ الدُّنْيَا نُؤْتِهِۦ مِنْهَا وَمَا لَهُۥ فِى الَْٔاخِرَةِ مِن نَّصِيبٍ",
    "أَمْ لَهُمْ شُرَكَٰٓؤُا شَرَعُوا لَهُم مِّنَ الدِّينِ مَا لَمْ يَأْذَن بِهِ اللَّهُ  وَلَوْلَا كَلِمَةُ الْفَصْلِ لَقُضِىَ بَيْنَهُمْ  وَإِنَّ الظَّٰلِمِينَ لَهُمْ عَذَابٌ أَلِيمٌ",
    "تَرَى الظَّٰلِمِينَ مُشْفِقِينَ مِمَّا كَسَبُوا وَهُوَ وَاقِعٌ بِهِمْ  وَالَّذِينَ ءَامَنُوا وَعَمِلُوا الصَّٰلِحَٰتِ فِى رَوْضَاتِ الْجَنَّاتِ  لَهُم مَّا يَشَآءُونَ عِندَ رَبِّهِمْ  ذَٰلِكَ هُوَ الْفَضْلُ الْكَبِيرُ",
    "ذَٰلِكَ الَّذِى يُبَشِّرُ اللَّهُ عِبَادَهُ الَّذِينَ ءَامَنُوا وَعَمِلُوا الصَّٰلِحَٰتِ  قُل لَّآ أَسَْٔلُكُمْ عَلَيْهِ أَجْرًا إِلَّا الْمَوَدَّةَ فِى الْقُرْبَىٰ  وَمَن يَقْتَرِفْ حَسَنَةً نَّزِدْ لَهُۥ فِيهَا حُسْنًا  إِنَّ اللَّهَ غَفُورٌ شَكُورٌ",
    "أَمْ يَقُولُونَ افْتَرَىٰ عَلَى اللَّهِ كَذِبًا  فَإِن يَشَإِ اللَّهُ يَخْتِمْ عَلَىٰ قَلْبِكَ  وَيَمْحُ اللَّهُ الْبَٰطِلَ وَيُحِقُّ الْحَقَّ بِكَلِمَٰتِهِۦٓ  إِنَّهُۥ عَلِيمٌ بِذَاتِ الصُّدُورِ",
    "وَهُوَ الَّذِى يَقْبَلُ التَّوْبَةَ عَنْ عِبَادِهِۦ وَيَعْفُوا عَنِ السَّئَِّاتِ وَيَعْلَمُ مَا تَفْعَلُونَ",
    "وَيَسْتَجِيبُ الَّذِينَ ءَامَنُوا وَعَمِلُوا الصَّٰلِحَٰتِ وَيَزِيدُهُم مِّن فَضْلِهِۦ  وَالْكَٰفِرُونَ لَهُمْ عَذَابٌ شَدِيدٌ",
    "۞ وَلَوْ بَسَطَ اللَّهُ الرِّزْقَ لِعِبَادِهِۦ لَبَغَوْا فِى الْأَرْضِ وَلَٰكِن يُنَزِّلُ بِقَدَرٍ مَّا يَشَآءُ  إِنَّهُۥ بِعِبَادِهِۦ خَبِيرٌ بَصِيرٌ",
    "وَهُوَ الَّذِى يُنَزِّلُ الْغَيْثَ مِن بَعْدِ مَا قَنَطُوا وَيَنشُرُ رَحْمَتَهُۥ  وَهُوَ الْوَلِىُّ الْحَمِيدُ",
    "وَمِنْ ءَايَٰتِهِۦ خَلْقُ السَّمَٰوَٰتِ وَالْأَرْضِ وَمَا بَثَّ فِيهِمَا مِن دَآبَّةٍ  وَهُوَ عَلَىٰ جَمْعِهِمْ إِذَا يَشَآءُ قَدِيرٌ",
    "وَمَآ أَصَٰبَكُم مِّن مُّصِيبَةٍ فَبِمَا كَسَبَتْ أَيْدِيكُمْ وَيَعْفُوا عَن كَثِيرٍ",
    "وَمَآ أَنتُم بِمُعْجِزِينَ فِى الْأَرْضِ  وَمَا لَكُم مِّن دُونِ اللَّهِ مِن وَلِىٍّ وَلَا نَصِيرٍ",
    "وَمِنْ ءَايَٰتِهِ الْجَوَارِ فِى الْبَحْرِ كَالْأَعْلَٰمِ",
    "إِن يَشَأْ يُسْكِنِ الرِّيحَ فَيَظْلَلْنَ رَوَاكِدَ عَلَىٰ ظَهْرِهِۦٓ  إِنَّ فِى ذَٰلِكَ لََٔايَٰتٍ لِّكُلِّ صَبَّارٍ شَكُورٍ",
    "أَوْ يُوبِقْهُنَّ بِمَا كَسَبُوا وَيَعْفُ عَن كَثِيرٍ",
    "وَيَعْلَمَ الَّذِينَ يُجَٰدِلُونَ فِىٓ ءَايَٰتِنَا مَا لَهُم مِّن مَّحِيصٍ",
    "فَمَآ أُوتِيتُم مِّن شَىْءٍ فَمَتَٰعُ الْحَيَوٰةِ الدُّنْيَا  وَمَا عِندَ اللَّهِ خَيْرٌ وَأَبْقَىٰ لِلَّذِينَ ءَامَنُوا وَعَلَىٰ رَبِّهِمْ يَتَوَكَّلُونَ",
    "وَالَّذِينَ يَجْتَنِبُونَ كَبَٰٓئِرَ الْإِثْمِ وَالْفَوَٰحِشَ وَإِذَا مَا غَضِبُوا هُمْ يَغْفِرُونَ",
    "وَالَّذِينَ اسْتَجَابُوا لِرَبِّهِمْ وَأَقَامُوا الصَّلَوٰةَ وَأَمْرُهُمْ شُورَىٰ بَيْنَهُمْ وَمِمَّا رَزَقْنَٰهُمْ يُنفِقُونَ",
    "وَالَّذِينَ إِذَآ أَصَابَهُمُ الْبَغْىُ هُمْ يَنتَصِرُونَ",
    "وَجَزَٰٓؤُا سَيِّئَةٍ سَيِّئَةٌ مِّثْلُهَا  فَمَنْ عَفَا وَأَصْلَحَ فَأَجْرُهُۥ عَلَى اللَّهِ  إِنَّهُۥ لَا يُحِبُّ الظَّٰلِمِينَ",
    "وَلَمَنِ انتَصَرَ بَعْدَ ظُلْمِهِۦ فَأُولَٰٓئِكَ مَا عَلَيْهِم مِّن سَبِيلٍ",
    "إِنَّمَا السَّبِيلُ عَلَى الَّذِينَ يَظْلِمُونَ النَّاسَ وَيَبْغُونَ فِى الْأَرْضِ بِغَيْرِ الْحَقِّ  أُولَٰٓئِكَ لَهُمْ عَذَابٌ أَلِيمٌ",
    "وَلَمَن صَبَرَ وَغَفَرَ إِنَّ ذَٰلِكَ لَمِنْ عَزْمِ الْأُمُورِ",
    "وَمَن يُضْلِلِ اللَّهُ فَمَا لَهُۥ مِن وَلِىٍّ مِّن بَعْدِهِۦ  وَتَرَى الظَّٰلِمِينَ لَمَّا رَأَوُا الْعَذَابَ يَقُولُونَ هَلْ إِلَىٰ مَرَدٍّ مِّن سَبِيلٍ",
    "وَتَرَىٰهُمْ يُعْرَضُونَ عَلَيْهَا خَٰشِعِينَ مِنَ الذُّلِّ يَنظُرُونَ مِن طَرْفٍ خَفِىٍّ  وَقَالَ الَّذِينَ ءَامَنُوٓا إِنَّ الْخَٰسِرِينَ الَّذِينَ خَسِرُوٓا أَنفُسَهُمْ وَأَهْلِيهِمْ يَوْمَ الْقِيَٰمَةِ  أَلَآ إِنَّ الظَّٰلِمِينَ فِى عَذَابٍ مُّقِيمٍ",
    "وَمَا كَانَ لَهُم مِّنْ أَوْلِيَآءَ يَنصُرُونَهُم مِّن دُونِ اللَّهِ  وَمَن يُضْلِلِ اللَّهُ فَمَا لَهُۥ مِن سَبِيلٍ",
    "اسْتَجِيبُوا لِرَبِّكُم مِّن قَبْلِ أَن يَأْتِىَ يَوْمٌ لَّا مَرَدَّ لَهُۥ مِنَ اللَّهِ  مَا لَكُم مِّن مَّلْجَإٍ يَوْمَئِذٍ وَمَا لَكُم مِّن نَّكِيرٍ",
    "فَإِنْ أَعْرَضُوا فَمَآ أَرْسَلْنَٰكَ عَلَيْهِمْ حَفِيظًا  إِنْ عَلَيْكَ إِلَّا الْبَلَٰغُ  وَإِنَّآ إِذَآ أَذَقْنَا الْإِنسَٰنَ مِنَّا رَحْمَةً فَرِحَ بِهَا  وَإِن تُصِبْهُمْ سَيِّئَةٌ بِمَا قَدَّمَتْ أَيْدِيهِمْ فَإِنَّ الْإِنسَٰنَ كَفُورٌ",
    "لِّلَّهِ مُلْكُ السَّمَٰوَٰتِ وَالْأَرْضِ  يَخْلُقُ مَا يَشَآءُ  يَهَبُ لِمَن يَشَآءُ إِنَٰثًا وَيَهَبُ لِمَن يَشَآءُ الذُّكُورَ",
